-- Run this in your Supabase SQL editor to create the performances table

create table if not exists performances (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  date date not null,
  title text not null,
  venue text not null,
  event_type text default 'Festzelt',
  image_url text,
  featured boolean default false
);

-- Enable Row Level Security
alter table performances enable row level security;

-- Allow public read access
create policy "Public can read performances"
  on performances for select
  using (true);

-- Allow authenticated users to insert/update/delete
create policy "Authenticated users can insert performances"
  on performances for insert
  with check (auth.role() = 'authenticated');

create policy "Authenticated users can update performances"
  on performances for update
  using (auth.role() = 'authenticated');

create policy "Authenticated users can delete performances"
  on performances for delete
  using (auth.role() = 'authenticated');

-- Band members table
create table if not exists band_members (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text not null,
  role text not null,
  description text not null default '',
  image_url text,
  sort_order integer not null default 0
);

alter table band_members enable row level security;

create policy "Public can read band_members"
  on band_members for select
  using (true);

create policy "Authenticated users can insert band_members"
  on band_members for insert
  with check (auth.role() = 'authenticated');

create policy "Authenticated users can update band_members"
  on band_members for update
  using (auth.role() = 'authenticated');

create policy "Authenticated users can delete band_members"
  on band_members for delete
  using (auth.role() = 'authenticated');
